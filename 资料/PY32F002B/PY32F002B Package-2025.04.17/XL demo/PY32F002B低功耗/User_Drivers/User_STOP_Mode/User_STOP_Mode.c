#include "User_STOP_Mode.h"


/************************************
 * 进入低功耗模式
*************************************/
void STOP_EN(void)
{
    

    /* 低功耗模式 */
    RCC->APBENR1 |= (1<<28);//使能PWR时钟
    PWR->CR1 |= (1<<14);// 低功耗工作在STOP模式

    SCB->SCR |= (1<<2);//内核进入深度休眠模式
	__WFI();//等待中断唤醒
	SCB->SCR &= ~(1<<2);//清除标记位    
}





















